import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,readFileSync,writeFileSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createHash} from 'node:crypto';
import * as bridge from '../scripts/model-cycle-bridge.mjs';
let cp;try{cp=await import('../scripts/review-checkpoint.mjs')}catch{}
const source='def add(a, b):\n    return (a + b)\n',base='a'.repeat(40);
const sha=s=>createHash('sha256').update(s).digest('hex');
const builder=async({request})=>({proposal:{baseSha:request.baseSha,changes:[{path:'fixture.py',content:source}]},receipt:{kind:'unit-fake-not-inference'}});
const reviewer=async({request})=>{
 assert.equal(request.source,source);
 return {advisory:{verdict:'no_defect',reason:'Tested sum matches.',example:{a:2,b:3,actual:5,required:5}},receipt:{kind:'unit-fake-not-inference'}};
};
test('generated cycle passes newly generated bytes rather than a historical source specimen',async()=>{
 assert.equal(typeof bridge.runGeneratedSyntheticCycle,'function');
 const r=await bridge.runGeneratedSyntheticCycle({baseSha:base,builder,reviewer});
 assert.equal(r.reviewer.status,'ADVISORY_AGREEMENT');
 assert.equal(r.reviewer.sourceSha256,sha(source));
 assert.equal(r.generatedSource,source);
 assert.equal(r.builder.modelExecuted,false);
 assert.equal(r.reviewer.modelExecuted,false);
 assert.equal(r.state,'BLOCKED');
 assert.equal(r.releaseAuthorized,false);
});
test('checkpoint roundtrip binds source, review digest and Git HEAD without granting authority',async()=>{
 const dir=mkdtempSync(join(tmpdir(),'hq-checkpoint-'));
 try{
  const r=await bridge.runGeneratedSyntheticCycle({baseSha:base,builder,reviewer});
  const file=join(dir,'review.json');
  const saved=cp.saveReviewCheckpoint(file,{baseSha:base,source:r.generatedSource,review:r.reviewer});
  const loaded=cp.loadReviewCheckpoint(file,{baseSha:base,expectedDigest:saved.sha256});
  assert.equal(loaded.source,source);
  assert.equal(loaded.review.sourceSha256,sha(source));
  assert.equal(loaded.authority,'none');
  assert.equal(loaded.review.modelExecuted,false);
  assert.throws(()=>cp.saveReviewCheckpoint(file,{baseSha:base,source,review:r.reviewer}));
  assert.throws(()=>cp.loadReviewCheckpoint(file,{baseSha:'b'.repeat(40),expectedDigest:saved.sha256}));
  const tampered=JSON.parse(readFileSync(file,'utf8'));tampered.source=source.replace('+','-');
  writeFileSync(file,JSON.stringify(tampered));
  assert.throws(()=>cp.loadReviewCheckpoint(file,{baseSha:base,expectedDigest:saved.sha256}));
 }finally{rmSync(dir,{recursive:true,force:true})}
});
test('checkpoint refuses forged source binding and extra raw output fields',async()=>{
 const dir=mkdtempSync(join(tmpdir(),'hq-checkpoint-'));
 try{
  const r=await bridge.runGeneratedSyntheticCycle({baseSha:base,builder,reviewer});
  assert.throws(()=>cp.saveReviewCheckpoint(join(dir,'wrong.json'),{baseSha:base,source:source+' ',review:r.reviewer}));
  assert.throws(()=>cp.saveReviewCheckpoint(join(dir,'raw.json'),{baseSha:base,source,review:{...r.reviewer,rawResponse:'not approved for storage'}}));
 }finally{rmSync(dir,{recursive:true,force:true})}
});
